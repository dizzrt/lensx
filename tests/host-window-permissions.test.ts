import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { describe, expect, test } from '@rstest/core';

const root = resolve(import.meta.dirname, '..');
const read = (path: string) => readFileSync(join(root, path), 'utf8');
const quoted = (text: string) => [...text.matchAll(/"([a-z][a-z0-9_:-]*)"/gu)].map((match) => match[1]);
const inventory = read('src-tauri/command_inventory.rs');
const common = quoted(inventory.split('COMMON_COMMANDS')[1].split('];')[0]);
const development = quoted(inventory.split('DEVELOPMENT_COMMANDS')[1].split('];')[0]);
const permissions = read('src-tauri/permissions/host-windows.toml');
const grants = (id: string): string[] => {
  const entry = permissions.split('[[permission]]').find((entry) => entry.includes(`identifier = "${id}"`));
  if (!entry) throw new Error(`Missing permission ${id}`);
  return quoted(entry.split('commands.allow = [')[1].split(']')[0]);
};

describe('trusted Host window command permissions', () => {
  test('registers the explicit cfg-aware app manifest with exact handler coverage', () => {
    const build = read('src-tauri/build.rs');
    expect(build).toContain('tauri_build::AppManifest::new()');
    expect(build).toContain('.commands(commands)');
    expect(build).toContain('.permissions_path_pattern(permission_pattern)');
    expect(build).toContain('CARGO_FEATURE_PLUGIN_DEVELOPMENT_MODE');
    const handlers = [...read('src-tauri/src/lib.rs').matchAll(/tauri::generate_handler!\[([\s\S]*?)\]/gu)].map(
      (match) => [...match[1].matchAll(/\b\w+::(\w+)/gu)].map((item) => item[1]),
    );
    expect(handlers).toHaveLength(2);
    expect(new Set(handlers[0])).toEqual(new Set(common));
    expect(new Set(handlers[1])).toEqual(new Set([...common, ...development]));
    expect(permissions).not.toContain('main-application');
    expect(build).toContain('for command in &commands');
    expect(build).toContain('host-window-permissions.toml');
    expect(build).toContain('std::env::var_os("OUT_DIR")');
    expect(new Set(common).size).toBe(common.length);
    expect(new Set(development).size).toBe(development.length);
  });

  test('selects exact main WebView instead of granting its plugin siblings through Window matching', () => {
    const main = JSON.parse(read('src-tauri/capabilities/default.json'));
    const shell = JSON.parse(read('src-tauri/capabilities/detached-shell.json'));
    expect(main.windows).toBeUndefined();
    expect(main.webviews).toEqual(['main']);
    expect(shell.windows).toBeUndefined();
    expect(shell.webviews).toEqual(['plugin-window-*']);
    expect(shell.permissions).toEqual(['detached-shell']);
    expect(grants('detached-shell')).toEqual([
      'read_host_window_bootstrap',
      'subscribe_host_window',
      'read_host_window_snapshot',
      'release_host_window_subscription',
      'ready_host_window',
      'update_host_window_slot',
    ]);
    for (const retired of [
      'detach_plugin_window',
      'register_main_detach_control',
      'drag_host_window',
      'close_host_window',
    ]) {
      expect(common).not.toContain(retired);
      expect(development).not.toContain(retired);
      expect(permissions).not.toContain(retired);
    }
    for (const privileged of [
      'write_app_preferences',
      'coordinate_plugin_child_webview',
      'close_host_instance',
      'quit_plugin_windows',
    ]) {
      expect(grants('detached-shell')).not.toContain(privileged);
    }
  });

  test('keeps generated permissions ignored and channels bound to the actual caller', () => {
    expect(read('src-tauri/.gitignore')).toContain('/permissions/autogenerated/');
    const build = read('src-tauri/build.rs');
    expect(build).toContain('std::path::Path::new("permissions/autogenerated")');
    expect(build).toContain('std::fs::remove_dir_all(autogenerated)');
    for (const command of development) expect(permissions).not.toContain(command);
    const host = read('src-tauri/src/plugin_detached_window_host.rs');
    expect(host).toContain('channel_id.channel_on(webview)');
    expect(host).not.toContain('emit_to(');
    expect(host).not.toMatch(/EventTarget::(?:Any|Window|App)\b/u);
    expect(host).not.toContain('emit_all(');
    expect(read('package.json')).not.toContain('host-window-permissions');
  });

  test('Tauri watcher rules ignore generated ACL events while retaining maintained native inputs', () => {
    // Tauri parses .taurignore as Git ignore rules rooted at its parent. Use
    // an isolated worktree so this project's .gitignore cannot mask a missing rule.
    const watcherRoot = mkdtempSync(join(tmpdir(), 'lensx-tauri-watch-'));
    const ignore = join(root, 'src-tauri/.taurignore');
    const generated = ['permissions/autogenerated', 'permissions/autogenerated/quit_plugin_windows.toml'];
    const maintained = [
      'permissions',
      'permissions/host-windows.toml',
      'permissions/autogenerated-extra.toml',
      'nested/permissions/autogenerated/another.toml',
      'command_inventory.rs',
      'build.rs',
      'tauri.conf.json',
      'capabilities/default.json',
      'src/lib.rs',
    ];
    try {
      execFileSync('git', ['init', '--quiet', '--template='], { cwd: watcherRoot });
      const ignored = execFileSync(
        'git',
        ['-c', `core.excludesFile=${ignore}`, 'check-ignore', '--no-index', '--stdin'],
        {
          cwd: watcherRoot,
          encoding: 'utf8',
          input: `${[...generated, ...maintained].join('\n')}\n`,
        },
      );
      expect(ignored.trimEnd().split('\n')).toEqual(generated);
    } finally {
      rmSync(watcherRoot, { recursive: true, force: true });
    }
  });
});
