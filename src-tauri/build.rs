mod command_inventory;

fn main() {
    println!("cargo:rerun-if-changed=command_inventory.rs");
    println!("cargo:rerun-if-changed=permissions/host-windows.toml");
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_PLUGIN_DEVELOPMENT_MODE");
    let mut commands = command_inventory::COMMON_COMMANDS.to_vec();
    if std::env::var_os("CARGO_FEATURE_PLUGIN_DEVELOPMENT_MODE").is_some() {
        commands.extend_from_slice(command_inventory::DEVELOPMENT_COMMANDS);
    }
    // Tauri does not remove commands left by a previous feature build. Rebuild
    // only its exact ignored output so disabled commands cannot enter the ACL.
    let autogenerated = std::path::Path::new("permissions/autogenerated");
    if autogenerated.exists() {
        std::fs::remove_dir_all(autogenerated).expect("old generated app permissions must clear");
    }

    // Main grants use the same feature-specific inventory as invoke handlers.
    // Detached grants remain a narrow maintained allowlist, independent of it.
    let mut permissions = String::from(
        "# Generated by build.rs for this Cargo feature set.\n[[permission]]\nidentifier = \"main-application\"\ndescription = \"Commands available to the trusted main Host in this build.\"\ncommands.allow = [\n",
    );
    for command in &commands {
        permissions.push_str(&format!("  \"{command}\",\n"));
    }
    permissions.push_str("]\n\n");
    permissions.push_str(include_str!("permissions/host-windows.toml"));
    let permission_path = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap())
        .join("host-window-permissions.toml");
    std::fs::write(&permission_path, permissions)
        .expect("feature-specific app permissions must write");
    let permission_pattern = Box::leak(
        permission_path
            .to_string_lossy()
            .into_owned()
            .into_boxed_str(),
    );
    let commands = Box::leak(commands.into_boxed_slice());
    tauri_build::try_build(
        tauri_build::Attributes::new().app_manifest(
            tauri_build::AppManifest::new()
                .commands(commands)
                .permissions_path_pattern(permission_pattern),
        ),
    )
    .expect("Tauri application ACL build failed");
}
